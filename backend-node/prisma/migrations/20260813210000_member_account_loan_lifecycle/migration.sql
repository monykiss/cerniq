ADD COLUMN     "loan_stage" "LoanLifecycleStage",
ADD COLUMN     "original_principal" DECIMAL(18,2),
ADD COLUMN     "product_code" "CooperativaProductCode",
ADD COLUMN     "restructured" BOOLEAN NOT NULL DEFAULT false;

